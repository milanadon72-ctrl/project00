# 1. Запрашиваем шаблон, имена и возраст
template = input("Введите шаблон поздравления, в шаблоне можно использовать конструкцию {name} и {age}: ")
names_input = input("Список людей через запятую: ")
ages_input = input("Возраст людей через пробел: ")

# 2. Превращаем строки в списки
# Очищаем имена от случайных лишних пробелов с помощью генератора и метода .strip()
names_list = [name.strip() for name in names_input.split(',')]
# Возраст делим по пробелам
ages_list = ages_input.split()

print() # Пустая строка для красоты вывода

# 3. Создаем список для хранения финальной строки с именинниками
celebrants = []

# 4. Запускаем цикл по двум спискам одновременно с помощью zip()
for name, age in zip(names_list, ages_list):
    # Подставляем имя и возраст в шаблон и сразу выводим на экран
    print(template.format(name=name, age=age))
    
    # Собираем данные для итоговой строки (Имя Возраст)
    celebrants.append(f"{name} {age}")

print() # Еще одна пустая строка

# 5. Склеиваем всех именинников через запятую с пробелом
celebrants_str = ', '.join(celebrants)
print(f"Именинники: {celebrants_str}")